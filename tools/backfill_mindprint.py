# 媒介固有偏置：difficulty 差异最明显
MEDIA_BIAS = {
    "book":  {"difficultyScore": 0.3, "artistryScore": 0.2},
    "anime": {"difficultyScore": -0.6, "emotionScore": 0.3},
    "game":  {"difficultyScore": 0.4, "logicScore": 0.2},
    "music": {"difficultyScore": -1.0, "emotionScore": 0.4},
    "movie": {"difficultyScore": -0.3, "artistryScore": 0.3},
}

BASE = 8.0      # 六维基线
DEFAULT_DIFF = 5.0
CEIL = 9.8      # 六维上限：不取 10.0，给相似度计算留出区分梯度
FLOOR = 1.0


def _stable_jitter(title: str) -> float:
    """用标题哈希生成稳定的 -0.25~+0.25 抖动，避免同流派作品六维完全一致。
    必须是确定性的：同一作品每次运行得到相同结果。"""
    h = hashlib.md5(title.encode("utf-8")).hexdigest()
    return (int(h[:8], 16) % 501) / 1000.0 - 0.25


def derive_mindprint(work: dict):
    """推导单部作品的六维档案

    关键设计：多条规则命中时取「逐维最大值」而非求和，再做整体缩放。
    求和会导致命中 3~4 条规则的作品六维全部撞到 10.0 上限，均值失真、
    作品之间失去区分度（跨媒介配对就全靠"都很像"了）。
    """
    text = " ".join([
        str(work.get("category") or ""),
        " ".join(work.get("tags") or []),
        str(work.get("shortComment") or ""),
        str(work.get("review") or ""),
    ])

    matched = 0
    acc = [0.0] * 6
    for kw, delta in GENRE_RULES.items():
        if kw in text:
            matched += 1
            for i in range(6):
                # 取逐维最大幅度，避免多规则线性累加
                if abs(delta[i]) > abs(acc[i]):
                    acc[i] = delta[i]

    # 无流派命中时给一个中性偏审美的基线（书籍默认有文学性）
    if matched == 0:
        acc = [0.4, 0.8, 0.6, 0.2, 0.3, 0.5]

    # 命中越多说明标签越丰富，适度衰减以保持整体在合理区间
    if matched > 2:
        scale = 1.0 / (1.0 + 0.18 * (matched - 2))
        acc = [v * scale for v in acc]

    rating = work.get("rating")
    rating = float(rating) if rating else 8.0
    # rating 7.0~10.0 → -1.2 ~ +1.2 的整体强度偏移。
    # 系数取大是为了拉开作品间差距：原始 112 部档案中五维均值标准差约 0.4，
    # 若补全值全部挤在 8.8~9.5，相似度会集中在 96~99，跨媒介择优排序将失去区分度。
    strength = (rating - 8.5) * 0.8

    media = work.get("mediaType") or "book"
    bias = MEDIA_BIAS.get(media, {})

    jitter = _stable_jitter(str(work.get("title") or ""))

    result = {}
    for i, dim in enumerate(DIMS):
        if dim == "difficultyScore":
            val = DEFAULT_DIFF + acc[i] * 0.9 + strength * 0.5
        else:
            val = BASE + acc[i] + strength
        val += bias.get(dim, 0.0)
        # 抖动只施加在非难度维，保持难度可比性
        if dim != "difficultyScore":
            val += jitter
        result[dim] = round(min(CEIL, max(FLOOR, val)), 1)

    # 治愈与情感都偏低时不应给出高治愈（逻辑一致性）
    if result["emotionScore"] < 7.0 and result["healingScore"] > 8.5:
        result["healingScore"] = 8.5

    return result


def main():
    with open(SRC, encoding="utf-8") as f:
        data = json.load(f)

    works = data["works"]
    filled = 0
    by_media = {}

    for w in works:
        if w.get("mindprint"):
            continue
        w["mindprint"] = derive_mindprint(w)
        filled += 1
        m = w.get("mediaType") or "?"
        by_media[m] = by_media.get(m, 0) + 1

    # 同步更新导出时间戳的可追溯性说明
    data["mindprintBackfilled"] = {
        "filled": filled,
        "byMedia": by_media,
        "note": "为缺失心智档案的作品补全六维推导值（基于流派/标签/评分/媒介特征）",
    }

    with open(DST, "w", encoding="utf-8") as f:
        json.dump(data, f, ensure_ascii=False, indent=2)

    print(f"源文件: {SRC}")
    print(f"输出:   {DST}")
    print(f"补全:   {filled} 部")
    print(f"分布:   {by_media}")
    has = sum(1 for w in works if w.get("mindprint"))
    print(f"覆盖率: {has}/{len(works)}")


if __name__ == "__main__":
    main()
